/*
 * embed.c - Embeds the adaC standard library into the compiler.
 *
 * usage: embed <library-dir>
 * Reads <library-dir>/MODULES ("kind path" per line) and writes a C file that defines
 *     const AdacLibModule ADAC_LIBRARY[] = { {kind, path, source text}, ..., {0,0,0} };
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void emit_string(FILE *f) {
    int c;
    printf("\"");
    while ((c = fgetc(f)) != EOF) {
        if (c == '\n') printf("\\n\"\n\"");
        else if (c == '"' || c == '\\') printf("\\%c", c);
        else if (c == '\r') { }
        else if (c == '\t') printf("\\t");
        else putchar(c);
    }
    printf("\"");
}

int main(int argc, char **argv) {
    if (argc != 2) { fprintf(stderr, "usage: embed <library-dir>\n"); return 2; }
    char path[1024], line[512];
    snprintf(path, sizeof path, "%s/MODULES", argv[1]);
    FILE *idx = fopen(path, "r");
    if (!idx) { fprintf(stderr, "embed: could not open %s\n", path); return 1; }
    printf("/* GENERATED by src/tools/embed - do not edit */\n");
    printf("typedef struct { const char *kind, *path, *text; } AdacLibModule;\n");
    printf("const AdacLibModule ADAC_LIBRARY[] = {\n");
    while (fgets(line, sizeof line, idx)) {
        char kind[32], rel[400];
        if (line[0] == '#' || sscanf(line, "%31s %399s", kind, rel) != 2) continue;
        snprintf(path, sizeof path, "%s/%s", argv[1], rel);
        FILE *f = fopen(path, "rb");
        if (!f) { fprintf(stderr, "embed: could not open %s\n", path); return 1; }
        printf("{\"%s\", \"%s\",\n", kind, rel);
        emit_string(f);
        printf("},\n");
        fclose(f);
    }
    printf("{0, 0, 0}\n};\n");
    fclose(idx);
    return 0;
}
